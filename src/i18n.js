// Helper to get translated object properties (e.g. obj.title_ro, obj.title_en, or obj.title)
export function tProp(obj, prop) {
  const lang = getLanguage();
  
  // Exact language match on the object itself
  if (obj[`${prop}_${lang}`]) {
    return obj[`${prop}_${lang}`];
  }
  
  // Fallback to English (if not Italian)
  if (lang !== 'it' && obj[`${prop}_en`]) {
    return obj[`${prop}_en`];
  }
  
  // Primary fallback (Italian)
  if (obj[prop]) return obj[prop];

  // Centralized translation lookup for non-IT/EN languages
  if (lang !== 'it' && lang !== 'en' && obj.id && procedureTranslations[obj.id] && procedureTranslations[obj.id][prop]) {
    const trans = procedureTranslations[obj.id][prop][lang];
    if (trans) return trans;
  }

  return '';
}

